SMALL = 16      # on a device's disc
BIG = 28        # a moving thing's silhouette
SCALE = 4       # rendered larger, then box-filtered down for smooth edges


def render(inner, px, stroke, fill):
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="{px * SCALE}" '
           f'height="{px * SCALE}" fill="{"#000" if fill else "none"}" stroke="#000" stroke-width="{stroke}" '
           f'stroke-linecap="round" stroke-linejoin="round" color="#000">{inner}</svg>')
    png = subprocess.run(["rsvg-convert", "-f", "png"], input=svg.encode(), capture_output=True, check=True).stdout
    img = Image.open(io.BytesIO(png)).convert("RGBA").getchannel("A")
    return img.resize((px, px), Image.BOX).tobytes()


def c_array(name, data, px):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + px]) for i in range(0, len(data), px)]
    body = ",\n    ".join(rows)
    return (f"constexpr uint8_t {name}_px[] = {{\n    {body},\n}};\n"
            f"const lv_image_dsc_t {name} = {{\n"
            f"    {{LV_IMAGE_HEADER_MAGIC, LV_COLOR_FORMAT_A8, 0, {px}, {px}, {px}, 0}},\n"
            f"    sizeof({name}_px), {name}_px, nullptr}};\n")


def main():
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    enum = ", ".join(n for n, _, _ in ICONS)
    hdr = f"""// Generated by scripts/gen-icons.py from Kismet's web UI icons; don't edit.

#pragma once

#include <lvgl.h>

namespace kw {{

// The id the client sends with each marker (client/markers/markers.go)
enum class marker_icon : uint8_t {{ {enum}, count }};

// A8 masks, drawn in the phy colour: small on a device's disc, big (and a
// wider halo behind it) for things drawn along their heading
const lv_image_dsc_t *icon_small(marker_icon i);
const lv_image_dsc_t *icon_big(marker_icon i);
const lv_image_dsc_t *icon_halo(marker_icon i);
bool icon_rotates(marker_icon i);

}}
"""
    src = ["// Generated by scripts/gen-icons.py from Kismet's web UI icons; don't edit.\n",
           '#include "widget_icons.h"\n', "namespace kw {\n", "namespace {\n"]
    small, big, halo = [], [], []
    for name, inner, moving in ICONS:
        if not inner:
            small.append("nullptr"); big.append("nullptr"); halo.append("nullptr")
            continue
        src.append(c_array(f"small_{name}", render(inner, SMALL, 2.6, False), SMALL))
        small.append(f"&small_{name}")
        if moving:
            src.append(c_array(f"big_{name}", render(inner, BIG, 2, True), BIG))
            src.append(c_array(f"halo_{name}", render(inner, BIG, 5.5, True), BIG))
            big.append(f"&big_{name}"); halo.append(f"&halo_{name}")
        else:
            big.append("nullptr"); halo.append("nullptr")
    n = len(ICONS)
    rot = ", ".join("true" if m else "false" for _, _, m in ICONS)
    src.append(f"constexpr const lv_image_dsc_t *small_tab[{n}] = {{{', '.join(small)}}};\n"
               f"constexpr const lv_image_dsc_t *big_tab[{n}] = {{{', '.join(big)}}};\n"
               f"constexpr const lv_image_dsc_t *halo_tab[{n}] = {{{', '.join(halo)}}};\n"
               f"constexpr bool rot_tab[{n}] = {{{rot}}};\n")
    src.append("}\n")
    for fn, tab in (("icon_small", "small_tab"), ("icon_big", "big_tab"), ("icon_halo", "halo_tab")):
        src.append(f"const lv_image_dsc_t *{fn}(marker_icon i) {{\n"
                   f"    const auto n = static_cast<size_t>(i);\n"
                   f"    return n < {n} ? {tab}[n] : nullptr;\n}}\n")
    src.append(f"bool icon_rotates(marker_icon i) {{\n    const auto n = static_cast<size_t>(i);\n"
               f"    return n < {n} && rot_tab[n];\n}}\n")
    src.append("}\n")
    with open(os.path.join(root, "ui", "widget_icons.h"), "w") as f:
        f.write(hdr)
    with open(os.path.join(root, "ui", "widget_icons.cpp"), "w") as f:
        f.write("\n".join(src))
    print(f"{n - 1} icons")
    return 0


if __name__ == "__main__":
    sys.exit(main())
