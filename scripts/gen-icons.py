"""Render the map's device icons to A8 alpha masks for LVGL.

The paths are Kismet's web UI icons (http_data/js/core/icons.js and the phy
modules), 24x24 line art; the helicopter is drawn here in the same style.
Writes ui/widget_icons.h and ui/widget_icons.cpp; needs rsvg-convert and
Pillow.  The order of ICONS is the icon id sent by the client
(client/markers/markers.go).

    scripts/gen-icons.py
"""

